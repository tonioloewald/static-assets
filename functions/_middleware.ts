/*
WHO MAY READ THE CDN FROM A PAGE (Cloudflare Pages middleware, runs on every request).

(Folders whose metadata says `"cors": "any"` are open to every site: see OPEN
FOLDERS below. What follows is the rule for everything else.)

Cross-origin reads are allowed only from our own sites and from development:
*.tosijs.net, loewald.com and its subdomains, localhost / 127.0.0.1 / [::1] /
tosi.local on any port, a private network address (a headset loads the dev server
by the Mac's LAN IP, which changes), and this project's own *.pages.dev previews.
Tonio, 2026-10-31: "They'll all be on .tosijs.net sites for the time being";
2026-11-04: "We need to allow loewald.com and subdomains in" (learn3d.loewald.com,
the Blender book). A new consumer on another domain is added HERE.

This is NOT access control. CORS decides whether another site's JavaScript may READ
a file; anyone can still fetch the URL directly. It stops other sites building on
our CDN, nothing more. A licence that forbids extractable copies is not met by it
(see assets/awbmecreations/metadata.json).

`_headers` cannot do this: it sends one fixed value, and Access-Control-Allow-Origin
carries a single origin or `*`. So the origin is checked here and echoed back, with
`Vary: Origin` so a cache never hands one origin's answer to another. The rest of
the headers (credit, licence, Expose-Headers, Cache-Control) still come from
`_headers`, which mirror.ts generates.
*/

/*
OPEN FOLDERS. A folder whose metadata.json says `"cors": "any"` may be read by
ANY site (Tonio, 2026-11-02: the static assets Dramatis needs, which are all his
or open source, are served to anyone, so its exporter works on any site). The
list is open-cors.json, generated by bin/mirror.ts from the metadata: [path,
"any" | "tosijs"] pairs, the deepest match deciding. Everything else keeps the
rule below. A file there answers `Access-Control-Allow-Origin: *`.
*/
import OPEN from '../open-cors.json'

const CORS_RULES = OPEN as [string, 'any' | 'tosijs'][]

/** True when the deepest folder declaring `cors` above `path` says `any`. */
export const openPath = (path: string): boolean => {
  let decided: 'any' | 'tosijs' = 'tosijs'
  let depth = -1
  for (const [prefix, cors] of CORS_RULES) {
    const p = '/' + prefix
    if (path !== p && !path.startsWith(p + '/')) continue
    const d = prefix.split('/').length
    if (d > depth) {
      depth = d
      decided = cors
    }
  }
  return decided === 'any'
}

const ALLOWED: RegExp[] = [
  /^https:\/\/([a-z0-9-]+\.)*tosijs\.net$/,
  /^https:\/\/([a-z0-9-]+\.)*loewald\.com$/,
  /^https?:\/\/(localhost|127\.0\.0\.1|\[::1\]|tosi\.local)(:\d+)?$/,
  /^https?:\/\/(10(\.\d{1,3}){3}|192\.168(\.\d{1,3}){2}|172\.(1[6-9]|2\d|3[01])(\.\d{1,3}){2})(:\d+)?$/,
  /^https:\/\/([a-z0-9-]+\.)*cdn-tosijs\.pages\.dev$/,
]

export const allowedOrigin = (origin: string | null): boolean =>
  origin != null && ALLOWED.some((re) => re.test(origin))

interface Context {
  request: Request
  next: () => Promise<Response>
}

export const onRequest = async ({ request, next }: Context): Promise<Response> => {
  const origin = request.headers.get('Origin')
  const open = openPath(decodeURIComponent(new URL(request.url).pathname))
  const ok = open || allowedOrigin(origin)
  // An open folder answers `*`; otherwise the caller's own origin, if allowed.
  const allow = open ? '*' : origin

  if (request.method === 'OPTIONS') {
    const headers = new Headers({ Vary: 'Origin' })
    if (ok) {
      headers.set('Access-Control-Allow-Origin', allow!)
      headers.set('Access-Control-Allow-Methods', 'GET, HEAD, OPTIONS')
      const asked = request.headers.get('Access-Control-Request-Headers')
      if (asked) headers.set('Access-Control-Allow-Headers', asked)
      headers.set('Access-Control-Max-Age', '86400')
    }
    return new Response(null, { status: ok ? 204 : 403, headers })
  }

  const res = await next()
  const out = new Response(res.body, res)
  out.headers.delete('Access-Control-Allow-Origin')
  if (ok) out.headers.set('Access-Control-Allow-Origin', allow!)
  out.headers.append('Vary', 'Origin')
  return out
}
